@pytest.mark.parametrize("harness,name", [
    ("claude", ri.HOOK_NAME), ("antigravity", ri.ANTIGRAVITY_HOOK_NAME),
])
def test_hook_adoption_requires_header_and_keeps_original(tmp_path, monkeypatch, harness, name):
    import render_prompts

    config = tmp_path / "config"
    config.mkdir()
    hook = config / name
    original = "#!/usr/bin/env bash\nprintf 'user hook'\n# Generated by render-invariants. quoted\n"
    hook.write_text(original)
    settings = config / "settings.json"
    settings.write_text('{"other": true}')
    monkeypatch.setattr(render_prompts, "manifest_path", lambda repo: tmp_path / "manifest.json")
    with pytest.raises(SystemExit, match="--adopt"):
        ri.deploy(REPO, config, settings, tmp_path / "backups", False, harness)
    assert hook.read_text() == original
    assert settings.read_text() == '{"other": true}'
    ri.deploy(REPO, config, settings, tmp_path / "backups", False, harness, adopt=True)
    assert original in [path.read_text() for path in (tmp_path / "backups").iterdir()]
    assert hook.read_text().startswith("#!/usr/bin/env bash\n# Generated by render-invariants. ")
    assert render_prompts.load_manifest(REPO)[f"hooks:{harness}"]["path"] == str(hook)


def test_settings_replace_failure_preserves_settings_and_records_completed_hook(tmp_path, monkeypatch):
    import render_prompts

    hook_dir = tmp_path / "hooks"
    settings = tmp_path / "settings.json"
    original = '{"other": true}'
    settings.write_text(original)
    monkeypatch.setattr(render_prompts, "manifest_path", lambda repo: tmp_path / "manifest.json")
    replace = os.replace

    def interrupt(source, target):
        if target == settings:
            assert Path(source).parent == settings.parent
            raise OSError("settings replace failed")
        replace(source, target)

    monkeypatch.setattr(os, "replace", interrupt)
    with pytest.raises(OSError, match="settings replace failed"):
        ri.deploy(REPO, hook_dir, settings, tmp_path / "backups", False)
    hook = hook_dir / ri.HOOK_NAME
    assert hook.read_text() == ri.render_hook(ri.read_invariants(REPO))
    assert settings.read_text() == original
    assert set(render_prompts.load_manifest(REPO)) == {"hooks:claude"}
    assert not list(tmp_path.glob(".agents-*"))


