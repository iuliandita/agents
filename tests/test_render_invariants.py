    snippet = json.loads((tmp_path / "out" / ri.ANTIGRAVITY_SETTINGS_NAME).read_text(encoding="utf-8"))
    assert snippet["invariants"]["PreInvocation"][0]["command"] == ri.shell_quote(str(antigravity / ri.ANTIGRAVITY_HOOK_NAME))


