#!/usr/bin/env python3
"""Render subagent definitions from agents/*.md into harness-native files.

One source per agent, flat frontmatter, prompt body. The renderer resolves
model tier and effort per harness, maps abstract tool names, injects the hard
invariants, and writes build/agents/<harness>/. Deploy is explicit.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import tomllib
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from tempfile import TemporaryDirectory

